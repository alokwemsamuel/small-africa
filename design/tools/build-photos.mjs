// Downloads the photos listed in design/photos/manifest.json from the Unsplash CDN and writes
// responsive AVIF + WebP sizes to frontend/public/img/, plus a TS credits module.
// Run: npm run photos   (re-runs skip photos already downloaded)
import { mkdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const manifest = JSON.parse(readFileSync(join(root, 'design/photos/manifest.json'), 'utf8'));
const cache = join(root, 'design/photos/originals');
const out = join(root, 'frontend/public/img');

// Dish images appear in cards (≤ 400px wide) and detail views (≤ 800px); ambience goes full-bleed.
const DISH_WIDTHS = [400, 800, 1200];
const WIDE_WIDTHS = [800, 1280, 1920];

for (const p of manifest.photos) {
  const src = join(cache, `${p.file}.jpg`);
  mkdirSync(dirname(src), { recursive: true });
  if (!existsSync(src)) {
    const url = `https://images.unsplash.com/photo-${p.cdn}?fm=jpg&q=85&w=2400&fit=max`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${p.file}: HTTP ${res.status}`);
    writeFileSync(src, Buffer.from(await res.arrayBuffer()));
  }
  const widths = p.wide ? WIDE_WIDTHS : DISH_WIDTHS;
  const aspect = p.wide ? 16 / 10 : 4 / 3;
  mkdirSync(dirname(join(out, p.file)), { recursive: true });
  for (const w of widths) {
    const h = Math.round(w / aspect);
    const base = sharp(src).resize(w, h, { fit: 'cover', position: sharp.strategy.attention }).withMetadata({ exif: {} });
    await base.clone().avif({ quality: 50, effort: 5 }).toFile(join(out, `${p.file}-${w}.avif`));
    await base.clone().webp({ quality: 74 }).toFile(join(out, `${p.file}-${w}.webp`));
  }
  // Tiny blurred placeholder (inlined as a data URI while the real image loads).
  p.blur = 'data:image/webp;base64,' + (await sharp(src).resize(24).blur(1.2).webp({ quality: 40 }).toBuffer()).toString('base64');
  console.log('✓', p.file);
}

const credits = manifest.photos.map(({ file, unsplash, by, profile, alt, wide, blur }) => ({
  file, unsplash, by, profile, alt, wide: !!wide, blur,
}));
writeFileSync(
  join(root, 'frontend/src/content/photos.ts'),
  `// Generated by design/tools/build-photos.mjs: do not edit by hand.\n` +
    `export interface Photo { file: string; unsplash: string; by: string; profile: string; alt: string; wide: boolean; blur: string }\n` +
    `export const PHOTO_WIDTHS = { dish: ${JSON.stringify(DISH_WIDTHS)}, wide: ${JSON.stringify(WIDE_WIDTHS)} } as const;\n` +
    `export const PHOTOS: Record<string, Photo> = ${JSON.stringify(Object.fromEntries(credits.map((c) => [c.file, c])), null, 2)};\n`,
);
console.log(`Done: ${manifest.photos.length} photos → frontend/public/img`);
