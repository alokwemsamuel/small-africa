<?php

declare(strict_types=1);

/**
 * Exports the seeded demo database as the starting data for the browser-only demo build
 * (frontend/src/lib/demo/snapshot.json), used on GitHub Pages where there is no PHP or MySQL.
 *
 *   composer fresh && php bin/export-demo.php
 *
 * Never contains secrets: no password hashes, 2FA secrets, sessions, tokens, rate limits or
 * audit trail. The last 30 days of guest orders and all reservations are left out: the demo
 * generates them relative to the day it is opened, so the dashboard is always current.
 */

use App\Support\Config;
use App\Support\Database;

$container = require dirname(__DIR__) . '/bootstrap.php';
/** @var Config $config */
$config = $container->get(Config::class);
if ($config->isProduction()) {
    fwrite(STDERR, "Refusing to export with APP_ENV=production.\n");
    exit(1);
}
$db = $container->get(Database::class);

$tables = [
    'kitchens' => 'SELECT * FROM kitchens ORDER BY id',
    'categories' => 'SELECT * FROM categories ORDER BY id',
    'dishes' => 'SELECT * FROM dishes WHERE deleted_at IS NULL ORDER BY id',
    'dish_options' => 'SELECT * FROM dish_options ORDER BY id',
    'tasting_courses' => 'SELECT * FROM tasting_courses ORDER BY id',
    'settings' => 'SELECT setting_key, setting_value FROM settings',
    'opening_hours' => 'SELECT * FROM opening_hours ORDER BY day_of_week',
    'delivery_zones' => 'SELECT * FROM delivery_zones ORDER BY id',
    'seating_areas' => 'SELECT * FROM seating_areas ORDER BY id',
    'reservation_slots' => 'SELECT * FROM reservation_slots ORDER BY id',
    'event_packages' => 'SELECT * FROM event_packages ORDER BY id',
    'coupons' => "SELECT * FROM coupons WHERE code NOT LIKE 'MISS-%' ORDER BY id",
    'users' => 'SELECT id, role, staff_position, first_name, last_name, email, phone, email_verified_at, birthday, favourite_kitchen_id,
                referral_code, referred_by_user_id, marketing_opt_in, theme_preference, is_active, created_at FROM users ORDER BY id',
    'loyalty_accounts' => 'SELECT * FROM loyalty_accounts ORDER BY user_id',
    'wallet_ledger' => 'SELECT * FROM wallet_ledger ORDER BY id',
    'points_ledger' => 'SELECT * FROM points_ledger ORDER BY id',
    'wallet_topups' => 'SELECT * FROM wallet_topups ORDER BY id',
    'interest_runs' => 'SELECT * FROM interest_runs ORDER BY id',
    'referrals' => 'SELECT id, referrer_user_id, referred_user_id, status, reject_reason, qualifying_order_id, rewarded_at, created_at FROM referrals ORDER BY id',
    'rewards_catalog' => 'SELECT * FROM rewards_catalog ORDER BY id',
    'reward_vouchers' => 'SELECT * FROM reward_vouchers ORDER BY id',
    'customer_offers' => "SELECT * FROM customer_offers WHERE kind <> 'winback' ORDER BY id",
    'notifications' => 'SELECT * FROM notifications ORDER BY id',
    'addresses' => 'SELECT * FROM addresses ORDER BY id',
    'dine_in_visits' => 'SELECT * FROM dine_in_visits ORDER BY id',
    // Members' order history (guest checkouts are generated by the demo at run time).
    'orders' => 'SELECT * FROM orders WHERE user_id IS NOT NULL ORDER BY id',
    'order_items' => 'SELECT oi.* FROM order_items oi JOIN orders o ON o.id = oi.order_id WHERE o.user_id IS NOT NULL ORDER BY oi.id',
    'order_status_history' => 'SELECT h.* FROM order_status_history h JOIN orders o ON o.id = h.order_id WHERE o.user_id IS NOT NULL ORDER BY h.id',
    'payments' => "SELECT p.* FROM payments p LEFT JOIN orders o ON p.purpose = 'order' AND o.id = p.payable_id
                   WHERE p.purpose <> 'order' OR o.user_id IS NOT NULL ORDER BY p.id",
    'reviews' => 'SELECT id, user_id, author_name, dish_id, NULL AS order_id, rating, title, body, status, admin_reply, replied_at, created_at FROM reviews ORDER BY id',
    'event_enquiries' => 'SELECT * FROM event_enquiries ORDER BY id',
    'contact_messages' => 'SELECT * FROM contact_messages ORDER BY id',
];

$out = ['version' => 1, 'exportedAt' => date('Y-m-d H:i:s'), 'tables' => []];
foreach ($tables as $name => $sql) {
    $rows = $db->all($sql);
    foreach ($rows as &$row) {
        foreach ($row as $k => $v) {
            // Numbers as numbers (PDO returns DECIMAL/BIGINT as strings on some drivers).
            if (is_string($v) && preg_match('/^-?\d{1,15}$/', $v) && !in_array($k, ['phone', 'customer_phone', 'guest_phone', 'code', 'reference', 'period', 'setting_value'], true)) {
                $row[$k] = (int) $v;
            }
        }
    }
    unset($row);
    $out['tables'][$name] = $rows;
}
// Coupons start unused and popularity leaves out guest orders: the demo's generated orders
// count their own.
foreach ($out['tables']['coupons'] as &$c) {
    $c['times_used'] = 0;
}
unset($c);
$guestQty = array_column($db->all(
    "SELECT oi.dish_id, SUM(oi.quantity) AS qty FROM order_items oi JOIN orders o ON o.id = oi.order_id
     WHERE o.user_id IS NULL AND o.payment_status = 'paid' GROUP BY oi.dish_id",
), 'qty', 'dish_id');
foreach ($out['tables']['dishes'] as &$d) {
    $d['popularity'] = max(0, (int) $d['popularity'] - (int) ($guestQty[$d['id']] ?? 0));
}
unset($d);

$file = dirname(__DIR__, 2) . '/frontend/src/lib/demo/snapshot.json';
if (!is_dir(dirname($file))) {
    mkdir(dirname($file), 0775, true);
}
file_put_contents($file, json_encode($out, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));
printf("Wrote %s (%s KB): %s\n", $file, number_format(filesize($file) / 1024), implode(', ', array_map(static fn ($t, $r) => "{$t} " . count($r), array_keys($out['tables']), $out['tables'])));
